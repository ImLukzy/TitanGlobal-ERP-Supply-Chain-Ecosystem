-- TitanGlobal ERP: agentes aduaneros y declaraciones de aduana (módulo 17, spec modulo17-agentes-aduaneros-backend).
--
-- El padrón de agentes se identifica por RUC y por número de registro. Una declaración (DAM/DUA) pertenece a un
-- expediente de importación y a un agente; el servidor calcula los derechos de arancel. Un expediente solo puede tener
-- una declaración vigente (no anulada) a la vez: lo garantiza el índice único filtrado.
-- Las reglas CK_ repiten en la base lo que ya valida la API, como segunda defensa ante datos cargados por fuera.
-- Convención de nombres: CK_<Tabla>_<Regla>.

CREATE TABLE "AgentesAduaneros" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Ruc" character varying(11) NOT NULL,
    "RazonSocial" character varying(200) NOT NULL,
    "NumeroRegistro" character varying(20) NOT NULL,
    "Email" character varying(150),
    "Telefono" character varying(20),
    "Activo" boolean NOT NULL,
    "FechaRegistro" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_AgentesAduaneros" PRIMARY KEY ("Id"),
    CONSTRAINT "CK_AgentesAduaneros_Ruc" CHECK ("Ruc" ~ '^[0-9]{11}$')
);
CREATE UNIQUE INDEX "IX_AgentesAduaneros_Ruc" ON "AgentesAduaneros" ("Ruc");
CREATE UNIQUE INDEX "IX_AgentesAduaneros_NumeroRegistro" ON "AgentesAduaneros" ("NumeroRegistro");

CREATE TABLE "DeclaracionesAduana" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Numero" character varying(30) NOT NULL,
    "ExpedienteImportacionId" integer NOT NULL,
    "AgenteAduaneroId" integer NOT NULL,
    "Regimen" character varying(30) NOT NULL,
    "ValorAduanero" numeric(18,2) NOT NULL,
    "TasaArancelaria" numeric(5,2) NOT NULL,
    "DerechosArancel" numeric(18,2) NOT NULL,
    "Canal" character varying(10),
    "Estado" character varying(20) NOT NULL,
    "FechaNumeracion" timestamp with time zone,
    "FechaLevante" timestamp with time zone,
    "MotivoAnulacion" character varying(500),
    "FechaRegistro" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_DeclaracionesAduana" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_DeclaracionesAduana_ExpedientesImportacion_ExpedienteImportacionId" FOREIGN KEY ("ExpedienteImportacionId") REFERENCES "ExpedientesImportacion" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_DeclaracionesAduana_AgentesAduaneros_AgenteAduaneroId" FOREIGN KEY ("AgenteAduaneroId") REFERENCES "AgentesAduaneros" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "CK_DeclaracionesAduana_Regimen" CHECK ("Regimen" IN ('ImportacionConsumo', 'AdmisionTemporal', 'Deposito')),
    CONSTRAINT "CK_DeclaracionesAduana_ValorAduanero" CHECK ("ValorAduanero" > 0),
    CONSTRAINT "CK_DeclaracionesAduana_TasaArancelaria" CHECK ("TasaArancelaria" >= 0 AND "TasaArancelaria" <= 100),
    CONSTRAINT "CK_DeclaracionesAduana_DerechosArancel" CHECK ("DerechosArancel" >= 0),
    CONSTRAINT "CK_DeclaracionesAduana_Canal" CHECK ("Canal" IS NULL OR "Canal" IN ('Verde', 'Naranja', 'Rojo')),
    CONSTRAINT "CK_DeclaracionesAduana_Estado" CHECK ("Estado" IN ('Registrada', 'Numerada', 'Levantada', 'Anulada')),
    CONSTRAINT "CK_DeclaracionesAduana_CanalDesdeNumerada" CHECK ("Canal" IS NULL OR "Estado" <> 'Registrada'),
    CONSTRAINT "CK_DeclaracionesAduana_MotivoSoloAnulada" CHECK ("MotivoAnulacion" IS NULL OR "Estado" = 'Anulada')
);
CREATE UNIQUE INDEX "IX_DeclaracionesAduana_Numero" ON "DeclaracionesAduana" ("Numero");
CREATE INDEX "IX_DeclaracionesAduana_AgenteAduaneroId" ON "DeclaracionesAduana" ("AgenteAduaneroId");
CREATE UNIQUE INDEX "IX_DeclaracionesAduana_Expediente_Vigente" ON "DeclaracionesAduana" ("ExpedienteImportacionId") WHERE "Estado" <> 'Anulada';
