-- Módulo 52: notas de crédito y débito por línea de factura.
-- Una base local que ya registró el 024 puede ejecutar este archivo
-- explícitamente en una transacción si el esquema provisional está vacío.

DO $$
BEGIN
    IF to_regclass('public."NotasCreditoDebito"') IS NOT NULL THEN
        LOCK TABLE public."NotasCreditoDebito" IN ACCESS EXCLUSIVE MODE;
        IF NOT EXISTS (
            SELECT 1
            FROM pg_attribute
            WHERE attrelid = 'public."NotasCreditoDebito"'::regclass
              AND attname = 'Serie' AND NOT attisdropped
        ) OR to_regclass('public."DetallesNotaCreditoDebito"') IS NOT NULL THEN
            RAISE EXCEPTION 'El esquema del módulo 52 no es el provisional.';
        END IF;
        IF EXISTS (SELECT 1 FROM public."NotasCreditoDebito") THEN
            RAISE EXCEPTION 'Las notas globales existentes no tienen detalle de origen. Se conservaron todos los datos.';
        END IF;
        DROP TABLE public."NotasCreditoDebito";
    END IF;
END
$$;

CREATE SEQUENCE "SecuenciaNotasCredito" AS bigint;
CREATE SEQUENCE "SecuenciaNotasDebito" AS bigint;

CREATE TABLE "NotasCreditoDebito" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "FacturaId" integer NOT NULL,
    "Tipo" character varying(20) NOT NULL,
    "Numero" character varying(30) NOT NULL,
    "Moneda" character(3) NOT NULL,
    "Motivo" character varying(300) NOT NULL,
    "BaseImponible" numeric(18,2) NOT NULL,
    "ImporteImpuesto" numeric(18,2) NOT NULL,
    "Total" numeric(18,2) NOT NULL,
    "Estado" character varying(20) NOT NULL,
    "FechaCreacion" timestamp with time zone NOT NULL,
    "FechaEmision" date,
    "FechaAnulacion" timestamp with time zone,
    "MotivoAnulacion" character varying(300),
    CONSTRAINT "PK_NotasCreditoDebito" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_NotasCreditoDebito_Facturas_FacturaId"
        FOREIGN KEY ("FacturaId") REFERENCES "Facturas" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "CK_NotasCreditoDebito_Tipo" CHECK ("Tipo" IN ('Credito', 'Debito')),
    CONSTRAINT "CK_NotasCreditoDebito_Numero" CHECK (
        "Numero" ~ '^TMP-[0-9a-f]{16}$'
        OR ("Tipo" = 'Credito' AND "Numero" ~ '^NC-[0-9]{6,19}$')
        OR ("Tipo" = 'Debito' AND "Numero" ~ '^ND-[0-9]{6,19}$')
    ),
    CONSTRAINT "CK_NotasCreditoDebito_Moneda" CHECK ("Moneda" IN ('PEN', 'USD')),
    CONSTRAINT "CK_NotasCreditoDebito_Motivo" CHECK (char_length(btrim("Motivo")) BETWEEN 3 AND 300),
    CONSTRAINT "CK_NotasCreditoDebito_Total" CHECK (
        "BaseImponible" >= 0 AND "BaseImponible" <> 'NaN'::numeric
        AND "ImporteImpuesto" >= 0 AND "ImporteImpuesto" <> 'NaN'::numeric
        AND "Total" > 0 AND "Total" <> 'NaN'::numeric
        AND "Total" = "BaseImponible" + "ImporteImpuesto"
    ),
    CONSTRAINT "CK_NotasCreditoDebito_EstadoFechas" CHECK (
        ("Estado" = 'Borrador' AND "FechaEmision" IS NULL
            AND "FechaAnulacion" IS NULL AND "MotivoAnulacion" IS NULL)
        OR ("Estado" = 'Emitida' AND "FechaEmision" IS NOT NULL
            AND "FechaAnulacion" IS NULL AND "MotivoAnulacion" IS NULL)
        OR ("Estado" = 'Anulada' AND "FechaEmision" IS NOT NULL AND "FechaAnulacion" IS NOT NULL
            AND "MotivoAnulacion" IS NOT NULL AND char_length(btrim("MotivoAnulacion")) BETWEEN 3 AND 300)
    )
);

CREATE UNIQUE INDEX "IX_NotasCreditoDebito_Numero"
    ON "NotasCreditoDebito" ("Numero");
CREATE INDEX "IX_NotasCreditoDebito_FacturaId_Estado"
    ON "NotasCreditoDebito" ("FacturaId", "Estado");
CREATE INDEX "IX_NotasCreditoDebito_FechaCreacion"
    ON "NotasCreditoDebito" ("FechaCreacion");

CREATE TABLE "DetallesNotaCreditoDebito" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "NotaCreditoDebitoId" integer NOT NULL,
    "DetalleFacturaId" integer NOT NULL,
    "Cantidad" numeric(18,4) NOT NULL,
    "PrecioUnitario" numeric(18,2) NOT NULL,
    "PorcentajeImpuesto" numeric(18,6) NOT NULL,
    "BaseImponible" numeric(18,2) NOT NULL,
    "ImporteImpuesto" numeric(18,2) NOT NULL,
    "Total" numeric(18,2) NOT NULL,
    CONSTRAINT "PK_DetallesNotaCreditoDebito" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_DetallesNotaCreditoDebito_NotasCreditoDebito_NotaId"
        FOREIGN KEY ("NotaCreditoDebitoId") REFERENCES "NotasCreditoDebito" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_DetallesNotaCreditoDebito_DetallesFactura_DetalleFacturaId"
        FOREIGN KEY ("DetalleFacturaId") REFERENCES "DetallesFactura" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "CK_DetallesNotaCreditoDebito_Cantidad"
        CHECK ("Cantidad" > 0 AND "Cantidad" <> 'NaN'::numeric),
    CONSTRAINT "CK_DetallesNotaCreditoDebito_Importes" CHECK (
        "PrecioUnitario" > 0 AND "PrecioUnitario" <> 'NaN'::numeric
        AND "PorcentajeImpuesto" BETWEEN 0 AND 100 AND "PorcentajeImpuesto" <> 'NaN'::numeric
        AND "BaseImponible" >= 0 AND "BaseImponible" <> 'NaN'::numeric
        AND "ImporteImpuesto" >= 0 AND "ImporteImpuesto" <> 'NaN'::numeric
        AND "Total" >= 0 AND "Total" <> 'NaN'::numeric
        AND "BaseImponible" = round("Cantidad" * "PrecioUnitario", 2)
        AND "ImporteImpuesto" = round("BaseImponible" * "PorcentajeImpuesto" / 100, 2)
        AND "Total" = "BaseImponible" + "ImporteImpuesto"
    )
);

CREATE UNIQUE INDEX "IX_DetallesNotaCreditoDebito_NotaId_DetalleFacturaId"
    ON "DetallesNotaCreditoDebito" ("NotaCreditoDebitoId", "DetalleFacturaId");
CREATE INDEX "IX_DetallesNotaCreditoDebito_DetalleFacturaId"
    ON "DetallesNotaCreditoDebito" ("DetalleFacturaId");

-- Inicio rol FINANZAS del módulo 52
DO $$
DECLARE
    ultimo_id bigint;
    secuencia_usada boolean;
    maximo_id integer;
BEGIN
    LOCK TABLE "Roles" IN SHARE ROW EXCLUSIVE MODE;

    IF EXISTS (SELECT 1 FROM "Roles" WHERE "Id" = 7 AND "Codigo" <> 'FINANZAS') THEN
        RAISE EXCEPTION 'El Id 7 ya pertenece a otro rol. No se creó FINANZAS.';
    END IF;
    IF EXISTS (SELECT 1 FROM "Roles" WHERE upper(btrim("Codigo")) = 'FINANZAS' AND "Id" <> 7) THEN
        RAISE EXCEPTION 'El código FINANZAS ya pertenece a un Id distinto de 7.';
    END IF;

    INSERT INTO "Roles" ("Id", "Codigo", "Nombre", "Descripcion", "EsSistema")
    VALUES (7, 'FINANZAS', 'Finanzas', 'Operaciones financieras', FALSE)
    ON CONFLICT DO NOTHING;

    SELECT MAX("Id") INTO maximo_id FROM "Roles";
    SELECT last_value, is_called INTO ultimo_id, secuencia_usada FROM "Roles_Id_seq";
    IF ultimo_id < maximo_id OR (ultimo_id = maximo_id AND NOT secuencia_usada) THEN
        PERFORM setval(pg_get_serial_sequence('"Roles"', 'Id'), maximo_id, TRUE);
    END IF;
END
$$;
